/** Creates the built-in documentation when the FAQ has no sections at all. Returns the number of articles created. */
export async function seedFaqDocs(): Promise<number> {
  if ((await prisma.faqSection.count()) > 0) return 0;
  let created = 0;
  await prisma.$transaction(async (tx) => {
    for (const [sectionIndex, section] of FAQ_DOCS.entries()) {
      const row = await tx.faqSection.create({ data: { title: section.title, position: sectionIndex } });
      for (const [itemIndex, item] of section.items.entries()) {
        await tx.faqItem.create({ data: { sectionId: row.id, title: item.title, body: item.body, position: itemIndex } });
        created += 1;
      }
    }
    await writeAuditEvent(
      {
        actorType: AuditActorType.SYSTEM,
        source: "seed",
        action: "faq.seeded",
        entityType: "faq_section",
        entityId: "built-in",
        after: { sections: FAQ_DOCS.length, items: created },
      },
      tx,
    );
  });
  return created;
}
